// ---- Orders (built from product ids so totals always match the items) ----
const line = (productId: number, qty: number): OrderItem => {
  const p = PRODUCTS.find((x) => x.id === productId)!;
  return { productId, name: p.name, qty, price: p.price };
};

const order = (
  id: number,
  customer: string,
  type: OrderType,
  status: OrderStatus,
  createdAt: string,
  items: OrderItem[],
  paymentMethod: PaymentMethod,
  paymentStatus: PaymentStatus,
  staffId: number,
  table?: string,
): Order => ({
  id,
  number: `#${1040 + id}`,
  customer,
  type,
  status,
  createdAt,
  items,
  total: +items.reduce((sum, i) => sum + i.qty * i.price, 0).toFixed(2),
  paymentMethod,
  paymentStatus,
  staffId,
  table,
});

